% extra: try with bisection method from 0 -> 2

x_start = 0.5; % lower bound on interval to find root in
x_end = 1; % upper bound on interval to find root in 

[x_mids, y_mids, iterations_needed, success] = ...
    bisectionMethod(tolerance, iterations, x_start, x_end, @(x) function_03(x));

% print success if we've found a zero within iterations and tolerance
